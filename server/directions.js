function categoriesFor(category) {
    return groups.find(([name]) => name === category) || [category];
}

function directionOptions(forFilter) {
    return groups.map(([name, ...specialties]) => {
        const options = [`<option value="${name}">${forFilter && specialties.length ? 'Все направления · ' : ''}${name}</option>`,
        ...specialties.map(specialty => `<option>${specialty}</option>`)].join('');
        return specialties.length ? `<optgroup label="${name}">${options}</optgroup>` : options;
    }).join('');
}

function directionLinks() {
    return groups.map(([name]) => '<a class="direction-link" href="/pages/vacancies.html?category=' +
        encodeURIComponent(name) + '#list">' + name + '</a>').join('\n');
}

module.exports = { categoriesFor, directionOptions, directionLinks };
